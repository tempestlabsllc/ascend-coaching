import { guides, formatPrice } from "@/config/site";
import BuyButton from "@/components/BuyButton";
import GuideUnlock from "@/components/GuideUnlock";
import EliteUnlock from "@/components/EliteUnlock";
import { cookies } from "next/headers";
import { ELITE_COOKIE } from "@/elite";

export const metadata = { title: "Digital guides" };

export default async function ShopPage() {
  const elite = (await cookies()).get(ELITE_COOKIE)?.value === "1";
  return (
    <div className="mx-auto max-w-6xl px-4 py-16">
      <h1 className="text-4xl font-extrabold">Digital starter guides</h1>
      <p className="mt-2 mb-6 max-w-2xl text-black/60">Instant PDF downloads you can work through at your own pace. No coaching commitment needed.</p>
      <div className="mb-10"><EliteUnlock unlocked={elite} /></div>
      <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
        {guides.map((g) => {
          const free = g.priceCents === 0;
          return (
            <div key={g.id} className="flex flex-col overflow-hidden rounded-2xl border border-black/10 bg-card shadow-sm">
              {/* Thumbnails live in /public/guides/<id>.jpg (generated by guides-src/thumbs/make.js) */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={`/guides/${g.id}.jpg`} alt="" className="aspect-[16/9] w-full object-cover" />
              <div className="flex flex-1 flex-col p-5">
                <h2 className="mb-3 text-lg font-extrabold leading-snug">{g.title}</h2>
                <div className="flex items-center justify-between">
                  <span className="text-2xl font-extrabold">{g.comingSoon ? "Coming soon" : free ? "Free" : formatPrice(g.priceCents)}</span>
                  {g.pages > 0 && <span className="text-xs text-black/50">{g.pages} pages · PDF</span>}
                </div>
                <p className="mt-2 flex-1 text-sm text-black/70">{g.description}</p>
                <div className="mt-5">
                  {g.comingSoon
                    ? <span className="btn w-full cursor-default border-2 border-dashed border-brand/40 text-brand">Coming soon</span>
                    : elite
                    ? <a href={`/api/download?guide=${g.id}`} className="btn-primary w-full">Download free (Elite)</a>
                    : free
                    ? <GuideUnlock guideId={g.id} />
                    : <BuyButton kind="guide" id={g.id} label="Buy now" />}
                </div>
              </div>
            </div>
          );
        })}
        <div className="flex min-h-64 flex-col items-center justify-center rounded-2xl border-2 border-dashed border-brand/40 bg-mist p-8 text-center">
          <span className="text-4xl">📘</span>
          <h3 className="mt-3 text-lg font-bold">More guides coming soon</h3>
          <p className="mt-1 text-sm text-black/60">New starter guides are on the way. Check back soon.</p>
        </div>
      </div>
    </div>
  );
}
